function getServiceDb(): SupabaseClient {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SERVICE_KEY;
  if (!url || !key) throw new Error('Supabase service credentials not configured');
  return createClient(url, key, { auth: { persistSession: false } });
}

// ═══════════════════════════════════════════════════════════════════════════
// Feature-cache column metadata
// ═══════════════════════════════════════════════════════════════════════════

// The 20 context feature columns in training_feature_cache + the "default" value
// that, if present, indicates "not actually measured" (treated as missing for
// fill-rate purposes). These defaults match the ones returned by each extractor
// when it has no data.
const CACHE_FEATURE_DEFAULTS: Record<string, number[]> = {
  // creator trajectory — all defaults: 0 (momentum), 50 (avg/consistency), 365 (recency), 1 (label)
  feature_creator_momentum_30d:        [0],
  feature_creator_avg_vps_90d:         [50],
  feature_creator_viral_recency:       [365],
  feature_creator_consistency_score:   [50],
  feature_creator_trajectory_label:    [1],
  // cultural momentum — all zeros are the "no data" default
  feature_cultural_momentum_score:     [0],
  feature_trend_phase_encoded:         [0],
  feature_niche_activation_score:      [0],
  feature_cultural_timing_advantage:   [0],
  // audience quality
  feature_follower_count_log:          [0],
  feature_engagement_rate_estimate:    [0.03],
  feature_follower_growth_velocity:    [0],
  feature_audience_size_tier:          [1],
  feature_follower_quality_score:      [50],
  // distribution signals — 50 is the neutral baseline produced when no data
  feature_post_hour_score:             [50],
  feature_post_day_score:              [50],
  feature_hashtag_strategy_score:      [50],
  feature_sound_advantage_score:       [50],
  feature_early_velocity_signal:       [50],
  feature_distribution_composite:      [50],
};

const ALL_FEATURE_COLUMNS = Object.keys(CACHE_FEATURE_DEFAULTS);
// Binary features are excluded from min-max scaling (already 0/1).
const BINARY_FEATURES = new Set<string>(['feature_cultural_timing_advantage', 'dps_population_flag']);
const SCALABLE_FEATURES = ALL_FEATURE_COLUMNS.filter((c) => !BINARY_FEATURES.has(c));
const FILL_RATE_DENOMINATOR = ALL_FEATURE_COLUMNS.length; // 20

function isMissing(column: string, value: number | null | undefined): boolean {
  if (value === null || value === undefined) return true;
  const defaults = CACHE_FEATURE_DEFAULTS[column] || [];
  // Consider a value "missing" only when it exactly matches one of the recognized
  // default sentinels. Real measurements that happen to equal a default will be
  // counted as present — the false-positive cost is tiny vs. the alternative of
  // requiring out-of-band metadata per row.
  return defaults.some((d) => Math.abs((value as number) - d) < 1e-9);
}

// ═══════════════════════════════════════════════════════════════════════════
// Step 2 — filterTrainingRows
// ═══════════════════════════════════════════════════════════════════════════

interface RunRow {
  id: string;
  creator_id: string | null;
  video_id: string | null;
  actual_dps: number | null;
}

interface CreatorMeta {
  user_id: string;
  niche: string;
  follower_count: number | null;
  channel_handle: string | null;
}

async function fetchEligibleRuns(db: SupabaseClient): Promise<RunRow[]> {
  const pageSize = 1000;
  const rows: RunRow[] = [];
  let offset = 0;
  while (true) {
    const { data, error } = await db
      .from('prediction_runs')
      .select('id, creator_id, video_id, actual_dps')
      .eq('is_holdout', false)
      .not('actual_dps', 'is', null)
      .order('id', { ascending: true })
      .range(offset, offset + pageSize - 1);
    if (error) throw new Error(`Failed to query prediction_runs: ${error.message}`);
    if (!data || data.length === 0) break;
    rows.push(...(data as RunRow[]));
    if (data.length < pageSize) break;
    offset += pageSize;
  }
  return rows;
}

async function fetchCreatorMeta(db: SupabaseClient, creatorIds: string[]): Promise<Map<string, CreatorMeta>> {
  const map = new Map<string, CreatorMeta>();
  if (creatorIds.length === 0) return map;
  const chunkSize = 500;
  for (let i = 0; i < creatorIds.length; i += chunkSize) {
    const chunk = creatorIds.slice(i, i + chunkSize);
    const { data, error } = await db
      .from('onboarding_profiles')
      .select('user_id, selected_niche, niche_key, follower_count, channel_handle')
      .in('user_id', chunk);
    if (error) throw new Error(`Failed to query onboarding_profiles: ${error.message}`);
    for (const r of (data || []) as Array<{
      user_id: string;
      selected_niche: string | null;
      niche_key: string | null;
      follower_count: number | null;
      channel_handle: string | null;
    }>) {
      map.set(r.user_id, {
        user_id: r.user_id,
        niche: r.selected_niche || r.niche_key || '',
        follower_count: r.follower_count,
        channel_handle: r.channel_handle,
      });
    }
  }
  return map;
}

async function fetchHashtagsByVideoId(db: SupabaseClient, videoIds: string[]): Promise<Map<string, string[]>> {
  const map = new Map<string, string[]>();
  if (videoIds.length === 0) return map;
  const chunkSize = 500;
  for (let i = 0; i < videoIds.length; i += chunkSize) {
    const chunk = videoIds.slice(i, i + chunkSize);
    const { data, error } = await db
      .from('scraped_videos')
      .select('video_id, hashtags')
      .in('video_id', chunk);
    if (error) throw new Error(`Failed to query scraped_videos: ${error.message}`);
    for (const r of (data || []) as Array<{ video_id: string; hashtags: string[] | null }>) {
      map.set(r.video_id, Array.isArray(r.hashtags) ? r.hashtags : []);
    }
  }
  return map;
}

interface CacheRow {
  prediction_run_id: string;
  [key: string]: unknown;
}

async function fetchCacheRows(db: SupabaseClient, runIds: string[]): Promise<Map<string, CacheRow>> {
  const map = new Map<string, CacheRow>();
  if (runIds.length === 0) return map;
  const selectCols = ['prediction_run_id', ...ALL_FEATURE_COLUMNS].join(', ');
  const chunkSize = 500;
  for (let i = 0; i < runIds.length; i += chunkSize) {
    const chunk = runIds.slice(i, i + chunkSize);
    const { data, error } = await db
      .from('training_feature_cache')
      .select(selectCols)
      .in('prediction_run_id', chunk);
    if (error) throw new Error(`Failed to query training_feature_cache: ${error.message}`);
    for (const r of (data || []) as unknown as CacheRow[]) {
      map.set(r.prediction_run_id, r);
    }
  }
  return map;
}

function hasNicheHashtag(hashtags: string[], allowed: Set<string>): boolean {
  for (const tag of hashtags) {
    if (!tag) continue;
    const norm = (tag.startsWith('#') ? tag : `#${tag}`).toLowerCase();
    if (allowed.has(norm)) return true;
  }
  return false;
}

function computeFillRate(cache: CacheRow | undefined): number {
  if (!cache) return 0;
  let present = 0;
  for (const col of ALL_FEATURE_COLUMNS) {
    const v = cache[col] as number | null | undefined;
    if (!isMissing(col, v)) present++;
  }
  return present / FILL_RATE_DENOMINATOR;
}

export async function filterTrainingRows(params?: Partial<FilterParams>): Promise<FilteredSet> {
  const filterParams: FilterParams = { ...DEFAULT_FILTER_PARAMS, ...(params || {}), excludeHoldout: true };
  const db = getServiceDb();

  // 1) All eligible prediction_runs
  const runs = await fetchEligibleRuns(db);
  const totalEligible = runs.length;
  if (totalEligible === 0) {
    return { rows: [], count: 0, totalEligible: 0, filterParams };
  }

  // 2) Must have a cache row + meet fill-rate threshold
  const cacheByRunId = await fetchCacheRows(db, runs.map((r) => r.id));

  // 3) Creator lookup (for follower range + niche)
  const creatorIds = Array.from(new Set(runs.map((r) => r.creator_id).filter((v): v is string => !!v)));
  const creatorMeta = await fetchCreatorMeta(db, creatorIds);

  // 4) Hashtag lookup for each video
  const videoIds = Array.from(new Set(runs.map((r) => r.video_id).filter((v): v is string => !!v)));
  const hashtagsByVideoId = filterParams.requireNicheHashtag
    ? await fetchHashtagsByVideoId(db, videoIds)
    : new Map<string, string[]>();

  const keptIds: string[] = [];
  for (const run of runs) {
    // Cache + fill rate
    const cache = cacheByRunId.get(run.id);
    if (!cache) continue;
    const fillRate = computeFillRate(cache);
    if (fillRate < filterParams.minFillRate) continue;

    // Follower range (requires creator meta)
    if (!run.creator_id) continue;
    const meta = creatorMeta.get(run.creator_id);
    if (!meta) continue;
    const followers = meta.follower_count ?? 0;
    if (followers < filterParams.minFollowers || followers > filterParams.maxFollowers) continue;

    // Niche hashtag (skip when niche not in map or the filter is disabled)
    if (filterParams.requireNicheHashtag) {
      const allowed = getNicheHashtagSet(meta.niche);
      if (allowed) {
        if (!run.video_id) continue;
        const hashtags = hashtagsByVideoId.get(run.video_id) || [];
        if (!hasNicheHashtag(hashtags, allowed)) continue;
      }
      // allowed === null → unknown niche → pass-through (don't penalize)
    }

    keptIds.push(run.id);
  }

  return { rows: keptIds, count: keptIds.length, totalEligible, filterParams };
}

// ═══════════════════════════════════════════════════════════════════════════
// Step 3 — checkRowFloor
// ═══════════════════════════════════════════════════════════════════════════

export const MINIMUM_ROWS = 1500;

export function checkRowFloor(filteredCount: number): RowFloorResult {
  if (filteredCount >= MINIMUM_ROWS) {
    return { met: true, count: filteredCount, action: 'proceed' };
  }
  if (filteredCount >= 1000) {
    return {
      met: false,
      count: filteredCount,
      action: 'relax-followers',
      suggestion: 'Widen follower range to 500-2M and rerun filter',
    };
  }
  return {
    met: false,
    count: filteredCount,
    action: 'relax-all',
    suggestion: 'Remove hashtag filter and widen follower range to 500-2M',
  };
}

// ═══════════════════════════════════════════════════════════════════════════
// Step 4 — checkDPSDistribution (+ writes dps_population_flag when bimodal)
// ═══════════════════════════════════════════════════════════════════════════

async function fetchDpsForRuns(db: SupabaseClient, runIds: string[]): Promise<Map<string, number>> {
  const map = new Map<string, number>();
  if (runIds.length === 0) return map;
  const chunkSize = 500;
  for (let i = 0; i < runIds.length; i += chunkSize) {
    const chunk = runIds.slice(i, i + chunkSize);
    const { data, error } = await db
      .from('prediction_runs')
      .select('id, actual_dps')
      .in('id', chunk);
    if (error) throw new Error(`Failed to query prediction_runs for dps: ${error.message}`);
    for (const r of (data || []) as Array<{ id: string; actual_dps: number | null }>) {
      if (r.actual_dps !== null && r.actual_dps !== undefined) map.set(r.id, Number(r.actual_dps));
    }
  }
  return map;
}

async function setPopulationFlag(db: SupabaseClient, runIds: string[], flag: 0 | 1): Promise<void> {
  if (runIds.length === 0) return;
  const chunkSize = 200;
  for (let i = 0; i < runIds.length; i += chunkSize) {
    const chunk = runIds.slice(i, i + chunkSize);
    const { error } = await db
      .from('training_feature_cache')
      .update({ dps_population_flag: flag })
      .in('prediction_run_id', chunk);
    if (error) throw new Error(`Failed to set dps_population_flag=${flag}: ${error.message}`);
  }
}

export async function checkDPSDistribution(rowIds: string[]): Promise<DPSDistributionResult> {
  const db = getServiceDb();
  const dpsById = await fetchDpsForRuns(db, rowIds);
  const values = Array.from(dpsById.values());

  if (values.length === 0) {
    return {
      isBimodal: false,
      mean: 0, median: 0, stdDev: 0,
      popA: { count: 0, mean: 0 },
      popB: { count: 0, mean: 0 },
      flagAdded: false,
    };
  }

  const n = values.length;
  const mean = values.reduce((s, v) => s + v, 0) / n;
  const sorted = [...values].sort((a, b) => a - b);
  const median = n % 2 === 0 ? (sorted[n / 2 - 1] + sorted[n / 2]) / 2 : sorted[Math.floor(n / 2)];
  const variance = values.reduce((s, v) => s + (v - mean) ** 2, 0) / n;
  const stdDev = Math.sqrt(variance);

  const splitThreshold = 45;
  const popAIds: string[] = [];
  const popBIds: string[] = [];
  let popASum = 0, popBSum = 0;
  for (const [id, v] of dpsById.entries()) {
    if (v < splitThreshold) { popAIds.push(id); popASum += v; }
    else                    { popBIds.push(id); popBSum += v; }
  }
  const popAMean = popAIds.length > 0 ? popASum / popAIds.length : 0;
  const popBMean = popBIds.length > 0 ? popBSum / popBIds.length : 0;

  const isBimodal =
    popAIds.length > 50 &&
    popBIds.length > 50 &&
    Math.abs(popAMean - popBMean) > 15;

  let flagAdded = false;
  if (isBimodal) {
    await setPopulationFlag(db, popAIds, 0);
    await setPopulationFlag(db, popBIds, 1);
    flagAdded = true;
    console.log(
      `[dataset-prep] DPS bimodal detected. ` +
      `Population A: ${popAIds.length} rows mean ${popAMean.toFixed(2)}, ` +
      `Population B: ${popBIds.length} rows mean ${popBMean.toFixed(2)}. ` +
      `dps_population_flag added as feature 79.`,
    );
  }

  return {
    isBimodal,
    mean, median, stdDev,
    popA: { count: popAIds.length, mean: popAMean },
    popB: { count: popBIds.length, mean: popBMean },
    flagAdded,
  };
}

// ═══════════════════════════════════════════════════════════════════════════
// Step 5 — computeScalingParams (writes to feature_scaling_params)
// ═══════════════════════════════════════════════════════════════════════════

export async function computeScalingParams(rowIds: string[]): Promise<ScalingParams> {
  const db = getServiceDb();
  if (rowIds.length === 0) {
    return { featuresScaled: 0, params: [] };
  }

  const cacheByRunId = await fetchCacheRows(db, rowIds);

  const entries: ScalingParamEntry[] = [];
  for (const col of SCALABLE_FEATURES) {
    let min = Number.POSITIVE_INFINITY;
    let max = Number.NEGATIVE_INFINITY;
    let count = 0;
    for (const runId of rowIds) {
      const cache = cacheByRunId.get(runId);
      if (!cache) continue;
      const v = cache[col] as number | null | undefined;
      if (v === null || v === undefined || Number.isNaN(v as number)) continue;
      const num = Number(v);
      if (num < min) min = num;
      if (num > max) max = num;
      count++;
    }
    if (count === 0) {
      entries.push({ feature_name: col, min_val: 0, max_val: 0, row_count: 0 });
      continue;
    }
    // Constant-feature guard: flagged by equal min/max. Consumers must map
    // (value - min) / (max - min) to 0.5 when max === min (handled at scale time).
    entries.push({ feature_name: col, min_val: min, max_val: max, row_count: count });
  }

  const nowIso = new Date().toISOString();
  const upsertRows = entries.map((e) => ({ ...e, computed_at: nowIso }));
  const { error } = await db
    .from('feature_scaling_params')
    .upsert(upsertRows, { onConflict: 'feature_name' });
  if (error) throw new Error(`Failed to upsert feature_scaling_params: ${error.message}`);

  return { featuresScaled: entries.length, params: entries };
}

/**
 * Apply the (min, max) scaling to a single value. `scaled = (v - min) / (max - min)`,
 * with the constant-feature guard (max === min → 0.5).
 */
export function applyScaling(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return 0.5;
  if (max === min) return 0.5;
  return (value - min) / (max - min);
}

// ═══════════════════════════════════════════════════════════════════════════
// Prep-run recording
// ═══════════════════════════════════════════════════════════════════════════

export interface PrepRunRecord {
  totalEligible: number;
  totalAfterFilter: number;
  dpsMeanOriginal: number;
  dpsMeanNew: number;
  isBimodal: boolean;
  dpsPopulationFlagAdded: boolean;
  minRowFloorMet: boolean;
  scalingApplied: boolean;
  filterParams: FilterParams;
  notes?: string;
}

export async function recordPrepRun(record: PrepRunRecord): Promise<string | null> {
  const db = getServiceDb();
  const { data, error } = await db
    .from('training_prep_runs')
    .insert({
      total_eligible: record.totalEligible,
      total_after_filter: record.totalAfterFilter,
      dps_mean_original: record.dpsMeanOriginal,
      dps_mean_new: record.dpsMeanNew,
      is_bimodal: record.isBimodal,
      dps_population_flag_added: record.dpsPopulationFlagAdded,
      min_row_floor_met: record.minRowFloorMet,
      scaling_applied: record.scalingApplied,
      filter_params: record.filterParams,
      notes: record.notes ?? null,
    })
    .select('id')
    .single();
  if (error) {
    console.error('[dataset-prep] Failed to record prep run:', error.message);
    return null;
  }
  return (data as { id: string } | null)?.id ?? null;
}
