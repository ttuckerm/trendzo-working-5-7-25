/**
 * Training dataset preparation pipeline.
 *
 * Filters the raw eligible rows down to a coherent training set, runs two
 * diagnostic checks (row-count floor, DPS bimodality), and computes min-max
 * scaling params per feature. S6 reads the filtered row IDs + the scaling
 * params table directly.
 *
 * Schema notes (kept aligned with prior sessions):
 *   - prediction_runs has no `dps_score`; the real ground-truth column is `actual_dps`.
 *   - onboarding_profiles keys creators by `user_id` and niche via `selected_niche || niche_key`.
 *   - scraped_videos joins to creators via `creator_username` ↔ onboarding_profiles.channel_handle.
 *
 * The prompt references "78 features" total (20 context + 58 content). This module
 * only has column-level visibility into the 20 context features in
 * training_feature_cache, so fill-rate is computed over those 20. The 58 content
 * features are generated by the prediction pipeline for every completed run — their
 * presence is implied by the row existing in prediction_runs with actual_dps set.
 */

import { createClient, SupabaseClient } from '@supabase/supabase-js';

// ═══════════════════════════════════════════════════════════════════════════
// Types
// ═══════════════════════════════════════════════════════════════════════════

export interface FilterParams {
  minFollowers: number;
  maxFollowers: number;
  requireNicheHashtag: boolean;
  minFillRate: number;
  excludeHoldout: true; // always true — the type enforces this at the call site
}

export const DEFAULT_FILTER_PARAMS: FilterParams = {
  minFollowers: 1_000,
  maxFollowers: 1_000_000,
  requireNicheHashtag: true,
  minFillRate: 0.95,
  excludeHoldout: true,
};

export interface FilteredSet {
  rows: string[];
  count: number;
  totalEligible: number;
  filterParams: FilterParams;
}

export type RowFloorAction = 'proceed' | 'relax-followers' | 'relax-all';
export interface RowFloorResult {
  met: boolean;
  count: number;
  action: RowFloorAction;
  suggestion?: string;
}

export interface DPSDistributionResult {
  isBimodal: boolean;
  mean: number;
  median: number;
  stdDev: number;
  popA: { count: number; mean: number };
  popB: { count: number; mean: number };
  flagAdded: boolean;
}

export interface ScalingParamEntry {
  feature_name: string;
  min_val: number;
  max_val: number;
  row_count: number;
}

export interface ScalingParams {
  featuresScaled: number;
  params: ScalingParamEntry[];
}

