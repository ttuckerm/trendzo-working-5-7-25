// Niche → hashtag map
// ═══════════════════════════════════════════════════════════════════════════

const NICHE_HASHTAGS: Record<string, string[]> = {
  cooking:            ['#food', '#cooking', '#recipe', '#foodtok'],
  food:               ['#food', '#cooking', '#recipe', '#foodtok'],
  fitness:            ['#fitness', '#gym', '#workout', '#fitnessmotivation'],
  finance:            ['#finance', '#investing', '#money', '#personalfinance'],
  'personal-finance': ['#finance', '#investing', '#money', '#personalfinance'],
  beauty:             ['#beauty', '#makeup', '#skincare', '#beautytok'],
  gaming:             ['#gaming', '#gamer', '#twitch', '#games'],
};

function getNicheHashtagSet(niche: string | null | undefined): Set<string> | null {
  if (!niche) return null;
  const key = String(niche).toLowerCase().trim();
  const hashtags = NICHE_HASHTAGS[key];
  if (!hashtags) return null; // unknown niche — skip hashtag filter
  return new Set(hashtags.map((h) => h.toLowerCase()));
}

function normalizeHandle(h: string | null | undefined): string | null {
  if (!h) return null;
  const s = String(h).trim().toLowerCase();
  if (!s) return null;
  return s.startsWith('@') ? s.slice(1) : s;
}

